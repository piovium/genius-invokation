import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { prepareVitestResultCaches, captureVitestResultCaches, restoreVitestResultCaches,
  validateVitestResultCacheEvidence } from './vitest-result-cache.mjs';

const cacheRelative = 'node_modules/.vite/vitest/da39a3ee5e6b4b0d3255bfef95601890afd80709/results.json';
// Frozen bytes from the actual installed pinned Volar cache are parser input,
// not acceptance evidence. This portable fixture has no workspace dependency.
const originalBytes = fs.readFileSync(new URL('./fixtures/volar-vitest-results.json', import.meta.url));
assert.equal(crypto.createHash('sha256').update(originalBytes).digest('hex'),
  'f32a344b1a74399e8563443ca953dce8775b2c58cac085ca0810ace108002f0b');
const originalCache = JSON.parse(originalBytes);
const keys = originalCache.results.map(([key]) => key);

function fixture(t, count = 1) {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'tnb-vitest-cache-'));
  t.after(() => {
    const actual = fs.realpathSync.native(base);
    assert.equal(path.dirname(actual), fs.realpathSync.native(os.tmpdir()));
    assert.ok(path.basename(actual).startsWith('tnb-vitest-cache-'));
    fs.rmSync(actual, { recursive: true });
  });
  const directory = path.join(base, 'evidence');
  fs.mkdirSync(directory);
  const entries = [];
  for (let i = 0; i < count; i++) {
    const root = path.join(base, `repo-${i}`);
    const file = path.join(root, cacheRelative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, originalBytes);
    entries.push({ root: fs.realpathSync.native(root), file: fs.realpathSync.native(file), keys });
  }
  return { base, directory, entries };
}

function completedBytes(extra = 1) {
  const value = structuredClone(originalCache);
  value.results.forEach(([, result]) => { result.duration += extra; });
  return Buffer.from(JSON.stringify(value));
}

test('supervisor restores exact original cache bytes after preserving generated bytes', t => {
  const f = fixture(t);
  const generated = completedBytes();
  prepareVitestResultCaches(f.directory, f.entries);
  fs.writeFileSync(f.entries[0].file, generated);
  // This uses durable metadata alone, as an independent parent would after
  // losing the child collector's cleanup closure.
  restoreVitestResultCaches(f.directory);
  assert.deepEqual(fs.readFileSync(f.entries[0].file), originalBytes);
  assert.deepEqual(fs.readFileSync(path.join(f.directory, 'cache-0-before.bin')), originalBytes);
  assert.deepEqual(fs.readFileSync(path.join(f.directory, 'cache-0-after.bin')), generated);
  restoreVitestResultCaches(f.directory);
  assert.deepEqual(fs.readFileSync(f.entries[0].file), originalBytes);
  assert.equal(validateVitestResultCacheEvidence(f.directory, f.entries).files.length, 1);
  assert.throws(() => validateVitestResultCacheEvidence(f.directory,
    [{ ...f.entries[0], keys: [...keys, ':unapproved.spec.ts'] }]), /independent test inventory/);
  assert.throws(() => validateVitestResultCacheEvidence(f.directory,
    [{ ...f.entries[0], file: path.join(f.entries[0].root, 'results.json') }]), /approved input/);
  assert.throws(() => validateVitestResultCacheEvidence(f.directory, []), /omits or adds/);
  fs.writeFileSync(f.entries[0].file, generated);
  assert.throws(() => validateVitestResultCacheEvidence(f.directory, f.entries), /original byte sequence/);
  assert.deepEqual(fs.readFileSync(f.entries[0].file), generated, 'Validator must not restore files');
  restoreVitestResultCaches(f.directory);
  fs.writeFileSync(path.join(f.directory, 'cache-0-after.bin'), completedBytes(999));
  assert.throws(() => validateVitestResultCacheEvidence(f.directory, f.entries), /Generated cache hash changed/);
});

test('a concurrent metadata writer is preserved while other owned caches recover', t => {
  const f = fixture(t, 2);
  prepareVitestResultCaches(f.directory, f.entries);
  for (const entry of f.entries) fs.writeFileSync(entry.file, completedBytes());
  captureVitestResultCaches(f.directory);
  const concurrent = completedBytes(100);
  fs.writeFileSync(f.entries[0].file, concurrent);
  assert.throws(() => restoreVitestResultCaches(f.directory), AggregateError);
  assert.deepEqual(fs.readFileSync(f.entries[0].file), concurrent);
  assert.deepEqual(fs.readFileSync(f.entries[1].file), originalBytes);
  const conflict = fs.readdirSync(f.directory).find(name => name.startsWith('cache-0-conflict-'));
  assert.deepEqual(fs.readFileSync(path.join(f.directory, conflict)), concurrent);
});

test('unrecognized fields or removed test keys are retained and block restoration', t => {
  for (const mutation of [value => { value.executable = 'unapproved'; }, value => value.results.pop(), value => { value.results[0][1].code = 'unapproved'; }]) {
    const f = fixture(t);
    prepareVitestResultCaches(f.directory, f.entries);
    const value = structuredClone(originalCache);
    mutation(value);
    const bytes = Buffer.from(JSON.stringify(value));
    fs.writeFileSync(f.entries[0].file, bytes);
    assert.throws(() => restoreVitestResultCaches(f.directory), AggregateError);
    assert.deepEqual(fs.readFileSync(f.entries[0].file), bytes);
    assert.deepEqual(fs.readFileSync(path.join(f.directory, 'cache-0-after.bin')), bytes);
  }
});

test('transform-cache changes remain visible and cannot be undone by this helper', t => {
  const f = fixture(t);
  const transform = path.join(path.dirname(f.entries[0].file), 'compiled.js');
  fs.writeFileSync(transform, 'before');
  prepareVitestResultCaches(f.directory, f.entries);
  fs.writeFileSync(f.entries[0].file, completedBytes());
  fs.writeFileSync(transform, 'changed transform');
  restoreVitestResultCaches(f.directory);
  assert.equal(fs.readFileSync(transform, 'utf8'), 'changed transform');
  assert.deepEqual(fs.readFileSync(f.entries[0].file), originalBytes);
});

test('missing or unrelated results.json and corrupted backups cannot be restored', t => {
  const f = fixture(t);
  const other = path.join(f.entries[0].root, 'results.json');
  fs.writeFileSync(other, originalBytes);
  assert.throws(() => prepareVitestResultCaches(f.directory, [{ ...f.entries[0], file: other }]), /default Vitest/);
  prepareVitestResultCaches(f.directory, f.entries);
  fs.writeFileSync(f.entries[0].file, completedBytes());
  fs.writeFileSync(path.join(f.directory, 'cache-0-before.bin'), 'corrupt');
  assert.throws(() => restoreVitestResultCaches(f.directory), AggregateError);
  assert.deepEqual(fs.readFileSync(f.entries[0].file), completedBytes());
});

test('a missing first cache does not prevent other recorded caches from recovering', t => {
  const f = fixture(t, 2);
  prepareVitestResultCaches(f.directory, f.entries);
  for (const entry of f.entries) fs.writeFileSync(entry.file, completedBytes());
  captureVitestResultCaches(f.directory);
  fs.unlinkSync(f.entries[0].file);
  assert.throws(() => restoreVitestResultCaches(f.directory), AggregateError);
  assert.equal(fs.existsSync(f.entries[0].file), false);
  assert.deepEqual(fs.readFileSync(f.entries[1].file), originalBytes);
});

test('a linked cache parent cannot redirect restoration outside the fixture', t => {
  const f = fixture(t);
  prepareVitestResultCaches(f.directory, f.entries);
  const cacheDirectory = path.dirname(f.entries[0].file);
  const originalDirectory = `${cacheDirectory}-original`;
  fs.renameSync(cacheDirectory, originalDirectory);
  fs.symlinkSync(originalDirectory, cacheDirectory, process.platform === 'win32' ? 'junction' : 'dir');
  assert.throws(() => restoreVitestResultCaches(f.directory), AggregateError);
  assert.deepEqual(fs.readFileSync(path.join(originalDirectory, 'results.json')), originalBytes);
});
